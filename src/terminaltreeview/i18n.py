def detect_language() -> str:
    try:
        language_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
    except (AttributeError, OSError):
        return "en"
    return "pt" if language_id & 0x3FF == 0x16 else "en"


def resolve(setting: str) -> str:
    return setting if setting in LANGUAGES else detect_language()


class Translator:
    def __init__(self, language: str = "auto"):
        self.language = resolve(language)
        self._table = STRINGS[self.language]

    def __call__(self, name: str, /, **values) -> str:
        text = self._table.get(name)
        if text is None:
            text = STRINGS["en"].get(name, name)
        return text.format(**values) if values else text
